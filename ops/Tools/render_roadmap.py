"""Render ROADMAP.md from AgentComms/roadmap.json.

    python Tools/render_roadmap.py

THE ROADMAP HAS ONE SOURCE AND THIS IS WHY. Today this project found eight
instances of the same defect: a fact authored in one place, hand-copied into a
second, and the copy drifting while a gate checked the copy. A hand-maintained
markdown roadmap beside a machine-readable one is that defect by construction.

So `AgentComms/roadmap.json` is the source. The ops board reads it directly.
This script renders the human copy. If you edit ROADMAP.md by hand your edit is
destroyed on the next run, which is the intended behaviour.
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "AgentComms", "roadmap.json")
OUT = os.path.join(ROOT, "ROADMAP.md")

BAR_WIDTH = 28


def bar(percent):
    filled = int(round(BAR_WIDTH * max(0, min(100, percent)) / 100.0))
    return "`" + ("#" * filled) + ("." * (BAR_WIDTH - filled)) + "`"


def main():
    with open(SRC, encoding="utf-8") as f:
        d = json.load(f)

    L = []
    L.append("# FightCamp — roadmap")
    L.append("")
    L.append("**GENERATED FROM `AgentComms/roadmap.json` by `Tools/render_roadmap.py`.**")
    L.append("Do not edit this file; edit the JSON and re-run. The ops board reads the")
    L.append("same JSON, so the board and this page can never disagree.")
    L.append("")
    L.append("Updated %s by %s." % (d.get("updated", "?"), d.get("author", "?")))
    L.append("")

    now = d.get("now", {})
    nxt = d.get("next", {})
    L.append("## Now")
    L.append("")
    # S34: `now` is keyed id/text and `next` is keyed session/summary - the same
    # two fields under four names. This renderer only knew the `next` vocabulary,
    # so the moment S33 was written ROADMAP.md rendered "? - <title>" with an
    # EMPTY body and nobody saw it, because the list-valued brief below crashed
    # the script before it ever wrote the file. Accept both spellings.
    L.append("**%s — %s** *(%s)*" % (
        now.get("session") or now.get("id", "?"), now.get("title", "?"),
        now.get("owner", "?")))
    L.append("")
    L.append(now.get("summary") or now.get("text", ""))
    L.append("")
    if now.get("gate"):
        L.append("**Gate:** %s" % now["gate"])
        L.append("")
    L.append("## Next")
    L.append("")
    # S64: `next` may be plain prose (S63 wrote it so) - render it as is.
    if isinstance(nxt, str):
        L.append(nxt)
        L.append("")
    else:
        L.append("**%s — %s** *(%s)*" % (
            nxt.get("session") or nxt.get("id", "?"), nxt.get("title", "?"),
            nxt.get("owner", "?")))
        L.append("")
        L.append(nxt.get("summary") or nxt.get("text", ""))
        L.append("")

    a = d.get("assessment", {})
    L.append("## Where the game actually is")
    L.append("")
    L.append("> %s" % a.get("one_line", ""))
    L.append("")
    L.append("Source: %s" % a.get("source", "?"))
    L.append("")
    L.append("| | | |")
    L.append("|---|---|---|")
    for b in a.get("bars", []):
        L.append("| %s | %s %d%% | %s |" % (b["label"], bar(b["percent"]), b["percent"], b["note"]))
    L.append("")

    L.append("## Stages")
    L.append("")
    for st in d.get("stages", []):
        L.append("### Stage %s — %s  %s %d%%" % (st["id"], st["title"], bar(st["percent"]), st["percent"]))
        L.append("")
        L.append("*%s*" % st["goal"])
        L.append("")
        L.append("Sessions: %s" % ", ".join(st.get("sessions", [])))
        L.append("")
        L.append("**Done when:**")
        for item in st.get("done_when", []):
            L.append("- %s" % item)
        L.append("")

    L.append("## The sessions")
    L.append("")
    L.append("An agent is briefed by `git fetch origin && git rebase origin/master && cat <brief>`")
    L.append("and nothing else. A multi-line prompt passed as a CLI argument arrives TRUNCATED —")
    L.append("Cursor once got a 50-line brief cut off at line 3 and said so.")
    L.append("")
    L.append("| | stage | session | owner | status | brief | what it is |")
    L.append("|---|---|---|---|---|---|---|")
    for s in d.get("sessions", []):
        marker = "**>>**" if s.get("status") == "in_progress" else ""
        brief = s.get("brief")
        # S34: a brief may be a LIST of paths, and `brief_exists` was a key
        # NOTHING ever wrote - so every brief rendered "(unwritten)" whatever
        # was on disk. Derive it from the filesystem instead of reading a
        # field that only ever held None.
        paths = brief if isinstance(brief, (list, tuple)) else [brief] if brief else []
        links = []
        for p in paths:
            p = str(p)
            name = p.rsplit("/", 1)[-1]
            if os.path.exists(os.path.join(ROOT, p.replace("/", os.sep))):
                links.append("[%s](%s)" % (name, p))
            else:
                links.append("`%s` **(unwritten)**" % name)
        link = "<br>".join(links) if links else "*none yet*"
        L.append("| %s | %s | **%s** %s | %s | %s | %s | %s |" % (
            marker, s.get("stage", ""), s.get("id", ""), s.get("title", ""),
            s.get("owner", ""), s.get("status", ""), link, s.get("summary", "")))
    L.append("")

    blocked = d.get("blocked_on_operator", [])
    if blocked:
        L.append("## Waiting on the operator")
        L.append("")
        L.append("Each of these blocks a session. Nothing below can start without a ruling.")
        L.append("")
        L.append("| | blocks | question |")
        L.append("|---|---|---|")
        for b in blocked:
            L.append("| **%s** | %s | %s |" % (b.get("id", "?"), b.get("blocks", ""), b.get("question", b.get("detail", ""))))
        L.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(L))
    print("wrote %s (%d stages, %d sessions, %d blocked)" % (
        OUT, len(d.get("stages", [])), len(d.get("sessions", [])), len(blocked)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
