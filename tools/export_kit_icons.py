"""Generates scripts/ui/KitIcon.gd from the mockups' icon set (docs/mockups/s403/kit.js), so the game draws the same icons the approved menus do (S403).
Usage: python tools/export_kit_icons.py   The icons live in the script as text and are rasterised at run time: no import step, nothing to add to the export."""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
src = (ROOT / "docs/mockups/s403/kit.js").read_text(encoding="utf-8")
block = src[src.index("const I = {"):src.index("function get(path)")]
rows = re.findall(r"^\s+'?([A-Za-z_ ]+?)'?: \['(.*?)', '(.*)'\],?$", block, flags=re.M)
def q(s: str) -> str:
    return '"' + s.replace("\'", "'").replace("\\", "\\\\").replace('"', '\\"') + '"'
body = ",\n".join(f"\t{q(n)}: [{q(p)}, {q(t)}]" for n, p, t in rows)
out = f'''extends RefCounted
## One icon per meaning, the same set as the approved menu mockups (docs/mockups/s403/icon_sheet.png). GENERATED by
## tools/export_kit_icons.py from kit.js: change the icon there. Each is line art drawn white and tinted by `colour`.

const ICONS := {{
{body}
}}

static var _cache := {{}}


static func has_icon(id: String) -> bool:
	return ICONS.has(id)


## What the icon means, for its tooltip.
static func tip(id: String) -> String:
	return String(ICONS[id][1]) if ICONS.has(id) else ""


static func tex(id: String, px: int = 24) -> Texture2D:
	var key := "%s@%d" % [id, px]
	if _cache.has(key):
		return _cache[key]
	if not ICONS.has(id):
		push_error("KitIcon: no icon " + id)
		return null
	var svg := '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" width="24" height="24" fill="none" stroke="#ffffff" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">%s</svg>' % String(ICONS[id][0])
	var img := Image.new()
	if img.load_svg_from_string(svg, float(px) / 24.0) != OK:
		push_error("KitIcon: bad icon " + id)
		return null
	var t := ImageTexture.create_from_image(img)
	_cache[key] = t
	return t


## An icon ready to add to a screen, with its tooltip. `why` replaces the default tooltip.
static func icon(id: String, px: int = 24, colour: Color = Color("22262e"), why: String = "") -> TextureRect:
	var r := TextureRect.new()
	r.texture = tex(id, px)
	r.modulate = colour
	r.expand_mode = TextureRect.EXPAND_IGNORE_SIZE
	r.stretch_mode = TextureRect.STRETCH_KEEP_ASPECT_CENTERED
	r.custom_minimum_size = Vector2(px, px)
	r.tooltip_text = why if why != "" else tip(id)
	r.mouse_filter = Control.MOUSE_FILTER_PASS
	return r
'''
(ROOT / "scripts/ui/KitIcon.gd").write_text(out, encoding="utf-8", newline="\n")
print(len(rows), "icons")
